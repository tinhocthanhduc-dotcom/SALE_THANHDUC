    assert((await page.locator("#search [role=option]").innerText()).includes("Nguyễn Bình"));
    await page.locator("#search input").press("Enter");
    assert((await page.locator("#detail h2").innerText()).includes("Nguyễn Bình"));
    await page.unroute(base + "/api");
    scenarios.push("late search response cannot replace the current query or select the wrong customer");
    if (process.env.CD_SCREENSHOTS) {
      fs.mkdirSync(process.env.CD_SCREENSHOTS, { recursive: true });
      await page.screenshot({ path: path.join(process.env.CD_SCREENSHOTS, "directory-390.png") });
    }
    await page.locator("#search .picker-clear").click();
    assert.equal(await page.locator("#search input").inputValue(), "");
    assert.equal(await page.locator("#detail h2").count(), 0);
