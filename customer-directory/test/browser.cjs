    sales.on("pageerror", (e) => errors.push(e.message));
    await sales.goto(base);
    await sales.locator("#nav").waitFor();
    await open(sales, "cong ty nguyen");
    await sales.locator("[data-edit]").click();
    assert.equal(await sales.locator("[name=TEN]").isDisabled(), true);
    assert.equal(await sales.locator("[name=MST]").isDisabled(), true);
    assert.equal(await sales.locator("[name=DIEN_THOAI]").isDisabled(), false);
