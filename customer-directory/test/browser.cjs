    await page.locator("[name=TEN]").fill("Khách mới từ ô tìm");
    await page.locator("#dialog [type=submit]").click();
    await page.waitForFunction(() => !document.querySelector("dialog").open);
    assert((await page.locator("#detail").innerText()).includes("Khách mới từ ô tìm"));
    scenarios.push("clear selection and create from no results with phone prefilled");
    await page.locator("#create").click();
    await page.locator("[name=TEN]").fill("Công ty trùng");
    await page.getByRole("radio", { name: "Công ty", exact: true }).check();
    await page.locator("[name=MST]").fill("0301234567");
    await page.locator("#dialog [type=submit]").click();
    await page.locator("#form-error button").waitFor();
    assert((await page.locator("#form-error").innerText()).includes("MST đã thuộc"));
    await page.locator("#form-error button").click();
    assert.equal(await page.locator("#detail h2").innerText(), "Công ty Nguyễn");
    scenarios.push("duplicate tax blocks creation and offers existing customer");
    await page.locator("#create").click();
    await page.locator("[name=TEN]").fill("Người liên hệ mới");
    await page.locator("[name=DIEN_THOAI]").fill("0901234567");
    await page.locator("#dialog [type=submit]").click();
    await page.getByRole("button", { name: "Thêm người liên hệ", exact: true }).click();
    assert.equal(await page.locator("[name=ten]").inputValue(), "Người liên hệ mới");
    await page.locator("#dialog [type=submit]").click();
    await page.waitForFunction(() => !document.querySelector("dialog").open);
    assert((await page.locator("#detail").innerText()).includes("Người liên hệ mới"));
    scenarios.push("shared company phone offers add contact without creating a duplicate customer");
